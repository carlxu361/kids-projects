(async () => {
  const response = await fetch('/birthday/card', { cache: 'no-store' });
  if (!response.ok) return;
  const card = await response.json();
  const grid = document.querySelector('[aria-labelledby="category-游戏"] .project-grid');
  const count = document.querySelector('.stats .stat strong');
  if (!grid || !count) return;
  const link = document.createElement('a');
  link.className = 'project-card';
  link.href = '/birthday';
  link.setAttribute('aria-label', card.title);
  const icon = document.createElement('span');
  icon.className = 'project-icon';
  icon.setAttribute('aria-hidden', 'true');
  icon.textContent = '🎂';
  const meta = document.createElement('span');
  meta.className = 'project-meta';
  const badge = document.createElement('span');
  badge.className = 'new-badge';
  badge.textContent = 'NEW';
  meta.append('游戏 · 20 ', badge, ' · 更新于 ' + card.date);
  const title = document.createElement('h3');
  title.textContent = card.title;
  const description = document.createElement('p');
  description.textContent = card.description;
  link.append(icon, meta, title, description);
  grid.append(link);
  count.textContent = String(Number(count.textContent) + 1);
})().catch(() => {});
